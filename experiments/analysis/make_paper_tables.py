"""Derive the manuscript-facing tables for the anchored headline (CeNN_AMS-Anc).

Inputs (all regenerated by experiments/aggregate.py + make_tables.py):
  experiments/aggregated/main_results.csv           seed-mean/std per (model, dataset, horizon)
  experiments/aggregated/tables/main_results.tex    12-method mean+-std table (bold/underline)
  experiments/aggregated/tables/significance.json   Friedman mean ranks
  experiments/results/*.json                        raw per-seed cells (for seed-paired controls)

Outputs (written to experiments/aggregated/paper_tables/, then inlined into the manuscript by hand):
  table_main_results_anchored.tex        tab:main_results   std-free, red = best / blue = second
  table_main_results_std_anchored.tex    source for the per-seed appendix tables (mean+-std) (mean+-std, 24 cols)
  table_profile_anchored.tex             tab:profile        mean rank / mean MSE / mean MAE / worst-case / params / MACs / latency
  table_regret28_anchored.tex            tab:regret28       per-cell regret distribution
  table_generic_trunk_anchored.tex       tab:generic_trunk  AMS-Anc vs MLPSkip-Anc, seeds {1,42,123}
  anchored_prose_numbers.md              every number the prose quotes (seed variability, skip-only vs full, frozen-skip control, ...)

Latency / params / MACs for the profile table are read from experiments/efficiency/*.json (see EFFICIENCY).
"""
