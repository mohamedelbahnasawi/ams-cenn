#!/usr/bin/env python
"""Uniform-preprocessing fairness table (appendix). For the four baselines that were re-run under
min--max, report seed-mean MSE under their reference (identity) scaler vs under AMS-CeNN's per-dataset
min--max, on the ETTh1/ETTh2 cells where the A/B was run. Shows min--max is NOT uniformly advantageous
(it helps DLinear, hurts the three baselines that outrank AMS-CeNN), so reporting each baseline under
its reference scaler is conservative toward the baselines.

Numbers are computed from the real result JSONs; a self-check asserts the per-model deltas match the
values stated in the manuscript's "Normalization Sensitivity" subsection.

Run: .venv/Scripts/python.exe experiments/analysis/make_preproc_table.py
"""
import sys, json, glob
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from experiments.config import RESULTS_DIR, EXPERIMENTS_DIR  # noqa: E402

ID_DIR = RESULTS_DIR                                   # canonical identity-scaler results
MM_DIRS = [EXPERIMENTS_DIR / "_scaler_ab_verify" / "results",
           EXPERIMENTS_DIR / "_scaler_ab" / "results",
           EXPERIMENTS_DIR / "_scaler_ab_h200" / "results",
           EXPERIMENTS_DIR / "_scaler_ab_h200"]  # h200 dump is flat (no results/ subdir)
MODELS = ["DLinear", "TSMixer", "iTransformer", "PatchTST"]
DSETS = ["ETTh1", "ETTh2"]


def cell_means(dirs, model):
    """(ds,H) -> seed-mean MSE, over the ETTh1/ETTh2 cells present in `dirs`."""
    dirs = dirs if isinstance(dirs, list) else [dirs]
    acc = {}
    for ds in DSETS:
        for d in dirs:
            for f in glob.glob(str(d / f"{model}__{ds}__H*__seed*.json")):
                try:
                    j = json.load(open(f)); acc.setdefault((ds, j["horizon"]), []).append(j["mse"])
                except Exception:
                    pass
    return {k: sum(v) / len(v) for k, v in acc.items()}


def main():
    rows = []
    for m in MODELS:
        idc = cell_means([ID_DIR], m)         # identity (reference) per cell
        mmc = cell_means(MM_DIRS, m)          # min--max per cell
        shared = sorted(set(idc) & set(mmc))  # matched cells only
        if not shared:
            print(f"[skip {m}: no shared cells]"); continue
        id_mean = sum(idc[c] for c in shared) / len(shared)
        mm_mean = sum(mmc[c] for c in shared) / len(shared)
        deltas = [mmc[c] - idc[c] for c in shared]
        dmean = sum(deltas) / len(deltas)
        dmax = max(deltas, key=abs)           # worst-cell change (signed)
        rows.append((m, id_mean, mm_mean, dmean, dmax))
        print(f"{m:14s} identity={id_mean:.3f}  minmax={mm_mean:.3f}  "
              f"Dmean={dmean:+.3f}  Dmax={dmax:+.3f}  cells={len(shared)} "
              f"({sorted(set(c[0] for c in shared))}x{sorted(set(c[1] for c in shared))})")

    # self-check vs manuscript "Normalization Sensitivity": DLinear ~-0.039 (mean), TSMixer ~+0.45,
    # iTransformer worst-cell up to +0.173, PatchTST worst-cell up to +0.231.
    cm = {r[0]: r for r in rows}
    print("\n[self-check] DLinear mean-delta ~ -0.039:", f"{cm['DLinear'][3]:+.3f}" if 'DLinear' in cm else "n/a")
    print("[self-check] iTransformer/PatchTST worst-cell (Dmax) ~ +0.173 / +0.231:",
          {k: round(cm[k][4], 3) for k in ('iTransformer', 'PatchTST') if k in cm})

    # emit LaTeX (Dmean + worst-cell Dmax, so the table is consistent with the text's "up to" maxes)
    lines = [r"% auto-generated by experiments/analysis/make_preproc_table.py",
             r"\begin{table}[!t]", r"\centering",
             r"\caption{Preprocessing-fairness check (seed-mean MSE on the matched ETTh1/ETTh2 cells "
             r"re-run under both scalers). Each re-run baseline is shown under its reference (identity) "
             r"normalization and under AMS-CeNN's per-dataset min--max; $\Delta$ is the mean change and "
             r"$\Delta_{\max}$ the worst-cell change. Min--max is \emph{not} uniformly advantageous: it "
             r"improves DLinear but degrades TSMixer, iTransformer, and PatchTST (the three baselines "
             r"that outrank AMS-CeNN), so reporting each baseline under its reference scaler is "
             r"conservative toward the baselines, not toward AMS-CeNN.}",
             r"\label{tab:preproc}",
             r"\begin{tabular}{lcccc}", r"\toprule",
             r"Baseline & Identity & Min--max & $\Delta$ & $\Delta_{\max}$ \\", r"\midrule"]
    for m, idm, mm, dl, dmx in rows:
        worse = dl > 0
        dstr = f"\\textbf{{{dl:+.3f}}}" if worse else f"{dl:+.3f}"
        lines.append(f"{m} & {idm:.3f} & {mm:.3f} & {dstr} & ${dmx:+.3f}$ \\\\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\\[2pt]\footnotesize Positive $\Delta$ = min--max \emph{hurts} the baseline. "
              r"DLinear is the only baseline min--max helps; it was nonetheless reported under identity.",
              r"\end{table}"]
    out = Path(__file__).resolve().parents[1] / "aggregated" / "tables" / "preproc_fairness.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"\n  wrote {out}")


if __name__ == "__main__":
    main()
